//! A CPU profile of the process in the pprof format.
//!
//! This works like Go's CPU profiler: each thread has a timer on its CPU time clock which sends it SIGPROF. Rather
//! than unwinding in the signal handler, the handler copies the thread's registers and the top of its stack into a
//! buffer, and the profiler thread unwinds them with the modules' DWARF unwind info. At the end of the recording, the
//! stacks are symbolized and written as a pprof profile.
use crate::debug::cpu_profile::pprof::{ProfileInfo, StackCount};
use crate::debug::cpu_profile::signal::{Buffer, Sample};
use crate::debug::cpu_profile::timers::Timers;
use crate::debug::Diagnostic;
use crate::unwind::Unwind;
use bytes::Bytes;
use conjure_error::{Conflict, Error};
use http::HeaderValue;
use parking_lot::Mutex;
use std::collections::HashMap;
use std::panic::{self, AssertUnwindSafe};
use std::thread;
use std::time::{Duration, Instant, SystemTime};

mod pprof;
// Generated by render-pprof from pprof's profile.proto.
#[allow(clippy::all)]
mod profile;
mod signal;
mod timers;

const DURATION: Duration = Duration::from_secs(60);
const PERIOD: Duration = Duration::from_millis(10);
/// How often the profiler thread unwinds buffered samples.
const DRAIN_INTERVAL: Duration = Duration::from_millis(10);
/// How often the profiler thread looks for new threads.
const SCAN_INTERVAL: Duration = Duration::from_millis(100);

static IN_PROGRESS: Mutex<()> = Mutex::new(());

/// A diagnostic which returns a 1 minute CPU profile of the process in the pprof format.
///
/// It is only supported on Linux.
pub struct CpuProfileDiagnostic;

impl Diagnostic for CpuProfileDiagnostic {
    fn type_(&self) -> &str {
        "rust.cpu.profile.v1"
    }

    fn content_type(&self) -> HeaderValue {
        HeaderValue::from_static("application/octet-stream")
    }

    fn safe_loggable(&self) -> bool {
        true
    }

    fn result(&self) -> Result<Bytes, Error> {
        record(DURATION).map(Bytes::from)
    }
}

fn record(duration: Duration) -> Result<Vec<u8>, Error> {
    let _guard = IN_PROGRESS.try_lock().ok_or_else(|| {
        Error::service_safe("a CPU profile is already in progress", Conflict::new())
    })?;

    signal::check_process_vm_readv()?;
    signal::install()?;

    let mut recorder = Recorder {
        unwind: Unwind::current_process(),
        frames: vec![],
        stacks: HashMap::new(),
    };

    let buffer = Buffer::new()?;
    let mut timers = Timers::new(PERIOD);

    let start_time = SystemTime::now();
    let start = Instant::now();
    let deadline = start + duration;
    let mut next_scan = start;
    loop {
        let now = Instant::now();
        if now >= next_scan {
            timers.scan()?;
            next_scan = now + SCAN_INTERVAL;
        }

        buffer.drain(|s| recorder.sample(s));

        if now >= deadline {
            break;
        }
        thread::sleep(Duration::min(DRAIN_INTERVAL, deadline - now));
    }
    let elapsed = start.elapsed();

    let names = timers.names().clone();
    drop(timers);
    buffer.drain(|s| recorder.sample(s));
    let dropped = buffer.dropped();
    drop(buffer);

    let info = ProfileInfo {
        start: start_time,
        duration: elapsed,
        period: PERIOD,
        dropped,
    };
    let stacks = recorder
        .stacks
        .iter()
        .map(|((tid, frames), count)| StackCount {
            tid: *tid,
            thread_name: names.get(tid).map_or("", |s| s),
            frames,
            count: *count,
        });

    Ok(pprof::build(&info, stacks, &recorder.unwind))
}

struct Recorder {
    unwind: Unwind,
    frames: Vec<u64>,
    stacks: HashMap<(i32, Vec<u64>), u64>,
}

impl Recorder {
    fn sample(&mut self, sample: &Sample) {
        let unwind = &mut self.unwind;
        let frames = &mut self.frames;
        // Unwinding interprets arbitrary stack contents, so a bug in the unwinder shouldn't take down the server.
        let result = panic::catch_unwind(AssertUnwindSafe(|| {
            unwind.unwind(&sample.regs, sample.regs.sp, sample.stack(), frames)
        }));
        if result.is_err() {
            self.unwind.reset_cache();
            return;
        }

        *self
            .stacks
            .entry((sample.tid, self.frames.clone()))
            .or_insert(0) += 1;
    }
}

